def _load(rel: str) -> Any:
    p = ROOT / rel
    if not p.is_file():
        raise FileNotFoundError(rel)
    return json.loads(p.read_text())


def _get(obj: dict, dotted: str) -> Any:
    cur: Any = obj
    for key in dotted.split("."):
        cur = cur[key]
    return cur


def _r(x: float, nd: int = 2) -> str:
    if nd == 0:
        return str(int(round(x)))
    return f"{round(x, nd):.{nd}f}"


def _pct(x: float, nd: int = 1) -> str:
    return _r(100 * x, nd)


def _pm(mean: float, sd: float, nd: int = 3) -> str:
    return f"{_r(mean, nd)} $\\pm$ {_r(sd, nd)}"


def _tex_num(x: float, nd: int = 2) -> str:
    s = _r(x, nd)
    if "." in s:
        a, b = s.split(".")
        return f"{int(a):,}".replace(",", "{,}") + "." + b if int(a) >= 1000 else s
    return s


def mae_r2_cell(mae: float, r2: float | None, mae_nd: int = 2, r2_nd: int = 3) -> str:
    if r2 is None:
        return f"\\textbf{{{_r(mae, mae_nd)}}}"
    return f"\\textbf{{{_r(mae, mae_nd)} ({_r(r2, r2_nd)})}}"


